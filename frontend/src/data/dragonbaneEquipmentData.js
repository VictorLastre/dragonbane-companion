export function convertirACobre(oro = 0, plata = 0, cobre = 0) {
  return (parseInt(oro, 10) || 0) * 100 + (parseInt(plata, 10) || 0) * 10 + (parseInt(cobre, 10) || 0);
}

export function formatearMonedas(cobreTotal) {
  const c = Math.max(0, parseInt(cobreTotal, 10) || 0);
  const oro = Math.floor(c / 100);
  const restoOro = c % 100;
  const plata = Math.floor(restoOro / 10);
  const cobre = restoOro % 10;
  
  const partes = [];
  if (oro > 0) partes.push(`${oro} MO`);
  if (plata > 0) partes.push(`${plata} MP`);
  if (cobre > 0 || partes.length === 0) partes.push(`${cobre} MC`);
  return partes.join(' ');
}

